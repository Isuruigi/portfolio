// Copies Axon's knowledge base, prompts and tool list from the site (../axon) into this project.
// LiveKit Cloud builds only this folder, so the agent can't import from outside it.
// Runs before `npm run dev`; run it by hand (`npm run sync`) before `lk agent deploy`.
// The copies are committed so a deploy from a clean checkout still has them. Never edit
// the copies: edit ../axon/knowledge.js or ../axon/prompt.js and sync again.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const from = join(here, "..", "..", "axon");
const to = join(here, "..", "src", "axon");
mkdirSync(to, { recursive: true });

for (const file of ["knowledge.js", "prompt.js", "stack.js"]) {
    const body = readFileSync(join(from, file), "utf8").replace(/\r\n/g, "\n");
    writeFileSync(join(to, file), `// GENERATED by scripts/sync-knowledge.mjs from axon/${file}. Do not edit this copy.\n${body}`);
    console.log(`synced axon/${file}`);
}
